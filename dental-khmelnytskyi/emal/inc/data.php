/** FAQ як блоки core/details: редагуються в редакторі, а схема FAQPage береться з того самого масиву. */
function emal_faq_blocks( $key ) {
	$items = emal_faqs()[ $key ] ?? array();
	$out   = '<!-- wp:heading {"className":"emal-faq-h"} --><h2 class="wp-block-heading emal-faq-h">Часті запитання</h2><!-- /wp:heading -->';
	foreach ( $items as $qa ) {
		$out .= '<!-- wp:details {"className":"emal-faq"} --><details class="wp-block-details emal-faq"><summary>' . esc_html( $qa[0] ) . '</summary>';
		$out .= '<!-- wp:paragraph --><p>' . esc_html( $qa[1] ) . '</p><!-- /wp:paragraph --></details><!-- /wp:details -->';
	}
	return $out;
}

